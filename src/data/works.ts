import type { Chapter, Work } from '@/types';

/**
 * Sample catalogue used to build and review the site experience.
 * It is isolated in this module so a real catalogue provider can replace it
 * without touching components, pages or styles.
 */

function makeChapters(count: number, lastPublishedAt: string, titles: string[] = []): Chapter[] {
  const last = new Date(`${lastPublishedAt}T09:00:00.000Z`).getTime();
  const day = 24 * 60 * 60 * 1000;
  return Array.from({ length: count }, (_, index) => {
    const number = index + 1;
    return {
      id: `ch-${number}`,
      number,
      title: titles[index] ?? `الفصل ${number}`,
      publishedAt: new Date(last - (count - 1 - index) * 7 * day).toISOString(),
    };
  });
}

